export const STRINGS = { en, hi }
export const LANGUAGES = Object.keys(STRINGS)

export function translate(lang, key, vars) {
  const text = STRINGS[lang]?.[key] ?? en[key] ?? key
  return vars ? text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? '')) : text
}

export function durationIn(lang, minutes) {
  if (minutes === null || minutes === undefined || Number.isNaN(Number(minutes))) return '-'
  const total = Math.max(0, Math.round(Number(minutes)))
  const h = Math.floor(total / 60)
  const m = total % 60
  return h > 0 ? translate(lang, 'duration.hm', { h, m }) : translate(lang, 'duration.m', { m })
}

// Text from the server that has a fixed set of English values, e.g. failure reasons
export function translateKnown(lang, prefix, value) {
  return STRINGS[lang]?.[`${prefix}.${value}`] ?? value
}
