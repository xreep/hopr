// Routing-engine benchmark. Generates reproducible delivery instances around the five
// demo hubs and compares the planner's search ('ils') with the previous search
// ('baseline'), with simple orders a dispatcher might use, and, where it can be
// computed, with the true optimum.
//
// Usage: npm run benchmark --workspace=backend   (writes docs/BENCHMARK.md)
import { writeFileSync } from 'node:fs'
import { bestSequence, evaluateSequence, planBatch } from '../src/services/routeOptimizer.js'
import { DEMO_CITIES } from '../src/data/indiaCities.js'
import { haversineKm } from '../src/utils/geo.js'
import { ROAD_CIRCUITY } from '../src/config/fleet.js'

const DEPARTURE = '2026-10-15T04:30:00.000Z' // Thursday 10:00 IST, mid-morning traffic
const VEHICLE = { type: 'van' }

function rng(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const hhmm = min => `${String(Math.floor(min / 60)).padStart(2, '0')}:${String(min % 60).padStart(2, '0')}`

// n stops spread within ~8 km of a city's hub; some with delivery windows and priorities
function instance(seed, n, { windows = true } = {}) {
  const r = rng(seed)
  const city = DEMO_CITIES[seed % DEMO_CITIES.length]
  const [lng, lat] = city.hub.coordinates
  const stops = Array.from({ length: n }, (_, i) => {
    const km = 8 * Math.sqrt(r())
    const angle = 2 * Math.PI * r()
    const stop = {
      address: `${city.city} delivery ${i + 1}`,
      coordinates: [lng + (km * Math.cos(angle)) / (111.32 * Math.cos((lat * Math.PI) / 180)), lat + (km * Math.sin(angle)) / 110.57],
      packageWeightKg: Math.round(1 + r() * 9),
      priority: r() < 0.15 ? 'urgent' : r() < 0.15 ? 'low' : 'standard'
    }
    if (windows && r() < 0.4) {
      const start = 600 + 30 + Math.floor(r() * 150 / 15) * 15
      stop.windowStart = hhmm(start)
      stop.windowEnd = hhmm(start + 60 + Math.floor(r() * 4) * 15)
    }
    return stop
  })
  return { depot: city.hub, stops, vehicle: VEHICLE, departureTime: DEPARTURE, city: city.city }
}

const cost = (inst, seq, objective = 'cost') => evaluateSequence(inst, seq, { objective })[objective === 'cost' ? 'cost' : 'distanceKm']

// Nearest-neighbour order by straight-line distance: what a dispatcher does by eye
function nearestNeighbour(inst) {
  const left = new Set(inst.stops.map((_, i) => i))
  const order = []
  let at = inst.depot.coordinates
  while (left.size) {
    let best = null
    for (const i of left) {
      const d = haversineKm(at, inst.stops[i].coordinates)
      if (!best || d < best.d) best = { i, d }
    }
    order.push(best.i)
    left.delete(best.i)
    at = inst.stops[best.i].coordinates
  }
  return order
}

// Exact shortest open path from the depot through every stop (Held-Karp), for the
// distance-only objective: the true optimum for up to ~16 stops
function heldKarp(inst) {
  const pts = [inst.depot.coordinates, ...inst.stops.map(s => s.coordinates)]
  const n = inst.stops.length
  const d = (a, b) => haversineKm(pts[a], pts[b]) * ROAD_CIRCUITY
  const full = (1 << n) - 1
  const dp = Array.from({ length: 1 << n }, () => new Float64Array(n).fill(Infinity))
  for (let j = 0; j < n; j++) dp[1 << j][j] = d(0, j + 1)
  for (let mask = 1; mask <= full; mask++) {
    for (let j = 0; j < n; j++) {
      const here = dp[mask][j]
      if (here === Infinity || !(mask & (1 << j))) continue
      for (let k = 0; k < n; k++) {
        if (mask & (1 << k)) continue
        const next = mask | (1 << k)
        const v = here + d(j + 1, k + 1)
        if (v < dp[next][k]) dp[next][k] = v
      }
    }
  }
  return Math.min(...dp[full])
}

const pct = (a, b) => (b > 0 ? ((a - b) / b) * 100 : 0)
const mean = xs => xs.reduce((s, x) => s + x, 0) / xs.length
const f1 = x => x.toFixed(1)
const f2 = x => x.toFixed(2)

const lines = []
const out = line => { lines.push(line); console.log(line) }

out('# Routing-engine benchmark')
out('')
out(`Generated by \`npm run benchmark --workspace=backend\` on ${new Date().toISOString().slice(0, 10)}. Instances are reproducible (seeded): stops spread within about 8 km of the five demo hubs (New Delhi, Mumbai, Bengaluru, Kolkata, Ranchi), 40% with a delivery window of 60–105 minutes, 15% urgent, departing 10:00 IST on a weekday. Costs use the planner's own model (driver time, fuel, late-window penalties, priority), as in section 4.2 of the technical documentation.`)
out('')
out('- **Hopr** is the search the planner uses: exact up to 8 stops, then local search with 2-opt, Or-opt chains and swaps, plus iterated local search.')
out('- **Previous** is the search used before: two starting orders improved with 2-opt and single-stop moves.')
out('- **Nearest neighbour** always drives to the closest remaining stop, which is roughly what planning by eye gives.')
out('')

// 1. Against the true optimum (exhaustive search over every order)
out('## 1. Against the true optimum')
out('')
out('| Stops | Instances | Hopr: optimal | Hopr: average gap | Previous: optimal | Previous: average gap | Nearest neighbour: average gap |')
out('|---|---|---|---|---|---|---|')
for (const n of [6, 8, 9]) {
  const rows = []
  for (let k = 0; k < 25; k++) {
    const inst = instance(1000 * n + k, n)
    const opt = bestSequence(inst, { strategy: 'exact', timeBudgetMs: 600000 }).cost
    const hopr = bestSequence(inst, { strategy: 'ils' }).cost
    const prev = bestSequence(inst, { strategy: 'baseline' }).cost
    const nn = cost(inst, nearestNeighbour(inst))
    rows.push({ hopr: pct(hopr, opt), prev: pct(prev, opt), nn: pct(nn, opt) })
  }
  const optimal = key => rows.filter(r => r[key] < 1e-6).length
  out(`| ${n} | ${rows.length} | ${optimal('hopr')}/${rows.length} | ${f2(mean(rows.map(r => r.hopr)))}% | ${optimal('prev')}/${rows.length} | ${f2(mean(rows.map(r => r.prev)))}% | ${f1(mean(rows.map(r => r.nn)))}% |`)
}
out('')
out('Gap = how much more the order costs than the best possible order. At 9 stops Hopr no longer searches exhaustively, so this row tests the heuristic itself.')
out('')

// 2. Shortest distance against Held-Karp
out('## 2. Shortest distance against the exact answer (Held–Karp)')
out('')
out('The "shortest distance" alternative the planner shows, compared with the exact shortest path computed by dynamic programming.')
out('')
out('| Stops | Instances | Hopr: optimal | Hopr: average gap | Nearest neighbour: average gap |')
out('|---|---|---|---|---|')
for (const n of [12, 15]) {
  const rows = []
  for (let k = 0; k < 15; k++) {
    const inst = instance(5000 * n + k, n, { windows: false })
    const opt = heldKarp(inst)
    const hopr = cost(inst, bestSequence(inst, { strategy: 'ils', objective: 'distance' }).sequence, 'distance')
    const nn = cost(inst, nearestNeighbour(inst), 'distance')
    rows.push({ hopr: pct(hopr, opt), nn: pct(nn, opt) })
  }
  out(`| ${n} | ${rows.length} | ${rows.filter(r => r.hopr < 1e-6).length}/${rows.length} | ${f2(mean(rows.map(r => r.hopr)))}% | ${f1(mean(rows.map(r => r.nn)))}% |`)
}
out('')

// 3. Larger routes, where no exact answer is practical
out('## 3. Larger routes')
out('')
out('No exact answer is practical here, so the searches are compared with each other. Saving = how much cheaper Hopr\'s order is.')
out('')
out('| Stops | Instances | Saving vs previous search | Better / same / worse than previous | Saving vs nearest neighbour | Saving vs order as entered | Hopr time (avg / max) |')
out('|---|---|---|---|---|---|---|')
for (const n of [15, 20, 30]) {
  const rows = []
  for (let k = 0; k < 15; k++) {
    const inst = instance(9000 * n + k, n)
    const hopr = bestSequence(inst, { strategy: 'ils' })
    const prev = bestSequence(inst, { strategy: 'baseline' }).cost
    const nn = cost(inst, nearestNeighbour(inst))
    const entered = cost(inst, inst.stops.map((_, i) => i))
    rows.push({ prev: -pct(hopr.cost, prev), nn: -pct(hopr.cost, nn), entered: -pct(hopr.cost, entered), ms: hopr.ms, cmp: Math.sign(prev - hopr.cost) })
  }
  const better = rows.filter(r => r.cmp > 0 && r.prev > 1e-6).length
  const worse = rows.filter(r => r.cmp < 0 && r.prev < -1e-6).length
  out(`| ${n} | ${rows.length} | ${f2(mean(rows.map(r => r.prev)))}% | ${better} / ${rows.length - better - worse} / ${worse} | ${f1(mean(rows.map(r => r.nn)))}% | ${f1(mean(rows.map(r => r.entered)))}% | ${Math.round(mean(rows.map(r => r.ms)))} / ${Math.max(...rows.map(r => r.ms))} ms |`)
}
out('')
out('Times are for the cost search on one route on the machine that ran the benchmark; the planner also runs a shorter shortest-distance search for the alternatives panel.')
out('')

// 4. Several vehicles: the sweep split alone against the split improved across vehicles
out('## 4. Several vehicles')
out('')
out('Stops are first split between vans by a sweep around the hub. Hopr then moves and swaps stops between vans while the total cost drops, and optimises each van\'s route. The comparison is the same batch planned without the moves between vans.')
out('')
out('| Stops / vans | Batches | Cost saving from moves between vans | Distance saving | Better / same / worse | Stops moved (avg) | Planning time (avg) |')
out('|---|---|---|---|---|---|---|')
for (const [n, vans, count] of [[40, 2, 8], [60, 3, 6], [90, 4, 4]]) {
  const rows = []
  for (let k = 0; k < count; k++) {
    const inst = instance(20000 * n + k, n)
    const vehicles = Array.from({ length: vans }, () => ({ type: 'van' }))
    const base = { depot: inst.depot, stops: inst.stops, vehicles, departureTime: DEPARTURE, includeAlternatives: false }
    const sweep = planBatch({ ...base, interRoute: false })
    const started = Date.now()
    const hopr = planBatch({ ...base, interRoute: true })
    const ms = Date.now() - started
    rows.push({
      cost: -pct(hopr.totals.operatingCost, sweep.totals.operatingCost),
      km: -pct(hopr.totals.distanceKm, sweep.totals.distanceKm),
      cmp: Math.sign(sweep.totals.operatingCost - hopr.totals.operatingCost),
      moved: hopr.totals.movedBetweenRoutes,
      ms
    })
  }
  const better = rows.filter(r => r.cmp > 0 && r.cost > 0.01).length
  const worse = rows.filter(r => r.cmp < 0 && r.cost < -0.01).length
  out(`| ${n} / ${vans} | ${rows.length} | ${f1(mean(rows.map(r => r.cost)))}% | ${f1(mean(rows.map(r => r.km)))}% | ${better} / ${rows.length - better - worse} / ${worse} | ${f1(mean(rows.map(r => r.moved)))} | ${f1(mean(rows.map(r => r.ms)) / 1000)} s |`)
}

writeFileSync(new URL('../../docs/BENCHMARK.md', import.meta.url), `${lines.join('\n')}\n`)
